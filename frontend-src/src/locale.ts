export type LocaleKey = keyof typeof messages;
export type UiLanguage = 'tr-TR' | 'en-US';

export function translate(language: UiLanguage, key: LocaleKey): string { return messages[key][language]; }

export function resolveLanguage(hass?: { locale?: { language?: string }; language?: string }): UiLanguage {
  const value = hass?.locale?.language || hass?.language || 'en-US';
  return value.replaceAll('_', '-').toLowerCase().startsWith('tr') ? 'tr-TR' : 'en-US';
}

export function formatLocalDate(value: string, language: UiLanguage, timeZone?: string): string {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return value;
  const options: Intl.DateTimeFormatOptions = { dateStyle: 'short', timeStyle: 'short' };
  if (timeZone) options.timeZone = timeZone;
  try { return new Intl.DateTimeFormat(language, options).format(date); }
  catch { delete options.timeZone; return new Intl.DateTimeFormat(language, options).format(date); }
}

export function formatLocalDuration(seconds: number, language: UiLanguage): string {
  const minutes = Math.round(seconds / 60);
  if (language === 'tr-TR') {
    if (minutes < 60) return `${minutes} dk`;
    const hours = Math.floor(minutes / 60); const remaining = minutes % 60;
    return remaining ? `${hours} sa ${remaining} dk` : `${hours} sa`;
  }
  if (minutes < 60) return `${minutes} min`;
  const hours = Math.floor(minutes / 60); const remaining = minutes % 60;
  return remaining ? `${hours} hr ${remaining} min` : `${hours} hr`;
}
